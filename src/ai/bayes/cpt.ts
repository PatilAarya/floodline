/**
 * The Floodline flood-risk network for the Mithi River basin, with its
 * conditional probability tables (CPTs), and the thresholds that turn live
 * simulation numbers into the network's discrete states.
 *
 *            Rain ───────────────┐
 *           │    │               │
 *           ▼    ▼               ▼
 *   RainGauge   RiverLevel ──► FloodRisk ◄── Drainage
 *                   │            ▲
 *                   ▼            │
 *              RiverGauge    Elevation
 *
 * Reading it: rain raises the river; rain, a high river, poor drains and low
 * ground all raise the flood risk of a place. We never see Rain or
 * RiverLevel directly, only two noisy sensors (a rain gauge and a river
 * gauge). Drainage and Elevation are known for each neighbourhood.
 *
 * Where the numbers come from (Mumbai-flavoured, rounded to 2 decimals):
 *   - Rain states use Mumbai's storm-drain design standard of 25 mm/h: below
 *     it the drains cope ("light"); 25-60 mm/h overwhelms them ("moderate");
 *     60 mm/h and more is a cloudburst-class hour ("heavy"). The prior is a
 *     monsoon day: mostly light rain, a heavy hour one time in five.
 *   - RiverLevel | Rain: heavy rain usually pushes the Mithi high; light rain
 *     rarely does (it can, at a spring high tide, which this model does not
 *     separate out).
 *   - The gauges are right about 80-90% of the time; when wrong they usually
 *     read one state off (a clogged tipping bucket, a debris-fouled stage
 *     sensor), rarely two. The SIMULATION injects exactly this noise when it
 *     produces readings, so the network's sensor model is honest.
 *   - FloodRisk has 81 rows (3 x 3 x 3 x 3 parent combinations), too many to
 *     invent one by one consistently. They are generated by an ordered
 *     logistic score (below), then rounded and printed as an explicit table
 *     on the Bayes page, where every number can be edited.
 */
import type { Network } from './network';

/** Variable indices in the network (stable: the UI and the engine use them). */
export const V = { Rain: 0, RiverLevel: 1, Drainage: 2, Elevation: 3, FloodRisk: 4, RainGauge: 5, RiverGauge: 6 } as const;

export const RAIN_STATES = ['light', 'moderate', 'heavy'];
export const RIVER_STATES = ['low', 'normal', 'high'];
export const DRAIN_STATES = ['poor', 'fair', 'good'];
export const ELEV_STATES = ['low', 'mid', 'high'];
export const RISK_STATES = ['low', 'medium', 'high'];

/** Rain-rate thresholds in mm/h: light < 25 <= moderate < 60 <= heavy. */
export const RAIN_MM_H = [25, 60] as const;
/**
 * River-gauge thresholds as a fraction of the way from the channel bed to
 * the top of the bank: low < 0.3 <= normal < 0.6 <= high. At the Mithi gauge
 * (bed about 2.7 m, bank about 5.15 m above sea) that is 3.4 m and 4.2 m.
 */
export const RIVER_FRAC = [0.3, 0.6] as const;
/** Ground elevation thresholds in metres above sea: low < 5 <= mid < 9 <= high. */
export const ELEV_M = [5, 9] as const;

export const rainClass = (mmPerHour: number): number => (mmPerHour < RAIN_MM_H[0] ? 0 : mmPerHour < RAIN_MM_H[1] ? 1 : 2);
export const elevClass = (metres: number): number => (metres < ELEV_M[0] ? 0 : metres < ELEV_M[1] ? 1 : 2);
export const drainClassIndex = (c: 'poor' | 'fair' | 'good'): number => DRAIN_STATES.indexOf(c);
export function riverClass(stage: number, bed: number, bank: number): number {
  const f = (stage - bed) / Math.max(0.1, bank - bed);
  return f < RIVER_FRAC[0] ? 0 : f < RIVER_FRAC[1] ? 1 : 2;
}

/**
 * Ordered logistic score for FloodRisk. Each parent adds "badness" points:
 *   z = 1.8 * rain + 1.2 * river + 0.6 * drainage + 2.0 * lowness
 * where rain, river = 0, 1, 2 (light/low .. heavy/high), drainage = 0 good,
 * 1 fair, 2 poor, and lowness = 0 high ground, 1 mid, 2 low. Rain and
 * elevation weigh most: the same rain that is a nuisance on a hill is a
 * disaster in Kurla's hollows, and without rain even the hollows stay
 * mostly dry. Then
 *   P(risk >= medium) = sigmoid(z - 4.5),   P(risk = high) = sigmoid(z - 7.5).
 * Examples: heavy rain, high river, fair drains, low ground: z = 10.6,
 * P(high) = 0.96. The same storm on high ground with good drains: z = 6.0,
 * mostly "medium" (waterlogging), P(high) = 0.18. A dry hour in a poorly
 * drained hollow: z = 5.2, P(high) = 0.09.
 */
export const RISK_WEIGHTS = { rain: 1.8, river: 1.2, drainage: 0.6, lowness: 2.0, cutMedium: 4.5, cutHigh: 7.5 } as const;

const sigmoid = (z: number) => 1 / (1 + Math.exp(-z));
const r2 = (p: number) => Math.round(p * 100) / 100;

function floodRiskRow(rain: number, river: number, drain: number, elev: number): number[] {
  const w = RISK_WEIGHTS;
  const z = w.rain * rain + w.river * river + w.drainage * (2 - drain) + w.lowness * (2 - elev);
  let high = r2(sigmoid(z - w.cutHigh));
  let low = r2(1 - sigmoid(z - w.cutMedium));
  high = Math.min(0.98, Math.max(0.01, high));
  low = Math.min(0.98, Math.max(0.01, low));
  if (low + high > 0.99) low = r2(0.99 - high);
  // Medium takes the remainder so the row sums to exactly 1 (to rounding).
  const medium = r2(1 - low - high);
  return [low, medium, high];
}

/** A fresh copy of the default Mumbai network. */
export function mumbaiNetwork(): Network {
  const fr: number[] = [];
  for (let r = 0; r < 3; r++) for (let v = 0; v < 3; v++) for (let d = 0; d < 3; d++) for (let e = 0; e < 3; e++) fr.push(...floodRiskRow(r, v, d, e));
  return {
    vars: [
      {
        name: 'Rain',
        about: 'How hard it is raining over the basin this hour (hidden: we only see the rain gauge).',
        states: RAIN_STATES,
        parents: [],
        cpt: Float64Array.of(0.5, 0.3, 0.2),
      },
      {
        name: 'RiverLevel',
        about: 'How high the Mithi River stands between its banks (hidden: we only see the river gauge).',
        states: RIVER_STATES,
        parents: [V.Rain],
        cpt: Float64Array.of(
          0.6, 0.35, 0.05, // light rain
          0.25, 0.55, 0.2, // moderate rain
          0.05, 0.35, 0.6, // heavy rain
        ),
      },
      {
        name: 'Drainage',
        about: 'How well the storm drains of a neighbourhood work (known per neighbourhood).',
        states: DRAIN_STATES,
        parents: [],
        cpt: Float64Array.of(0.3, 0.5, 0.2),
      },
      {
        name: 'Elevation',
        about: 'Ground height above sea: low below 5 m, mid 5 to 9 m, high above (known per place).',
        states: ELEV_STATES,
        parents: [],
        cpt: Float64Array.of(0.35, 0.4, 0.25),
      },
      {
        name: 'FloodRisk',
        about: 'Chance that this kind of place floods badly (roads closed, homes wet) under these conditions.',
        states: RISK_STATES,
        parents: [V.Rain, V.RiverLevel, V.Drainage, V.Elevation],
        cpt: Float64Array.from(fr),
      },
      {
        name: 'RainGauge',
        about: 'What the rain gauge reports. Right about 80-90% of the time.',
        states: RAIN_STATES,
        parents: [V.Rain],
        cpt: Float64Array.of(
          0.9, 0.08, 0.02, // truly light
          0.1, 0.8, 0.1, // truly moderate
          0.03, 0.12, 0.85, // truly heavy
        ),
      },
      {
        name: 'RiverGauge',
        about: 'What the river stage gauge reports. Right about 80-85% of the time.',
        states: RIVER_STATES,
        parents: [V.RiverLevel],
        cpt: Float64Array.of(
          0.85, 0.13, 0.02, // truly low
          0.1, 0.8, 0.1, // truly normal
          0.02, 0.13, 0.85, // truly high
        ),
      },
    ],
  };
}
